/// <summary>
/// 클라이언트 로컬 게임 상태. 활성 입력 액션맵과 커서 모드를 결정한다.
/// 멀티플레이이므로 어떤 상태도 게임 시간(Time.timeScale)을 멈추지 않는다 — 네트워크로 복제되지 않는 순수 로컬 값이다.
/// </summary>
public enum GameState
{
    Menu,  // 타이틀·로비 등 UI 전용 화면. UI 입력만 활성화된다.
    Game,  // 인게임 플레이 중. Gameplay 입력만 활성화된다.
    Pause, // 인게임 일시정지 메뉴. UI 입력만 활성화되며 게임 시간은 계속 흐른다.
}
